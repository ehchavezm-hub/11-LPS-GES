const { chromium } = require('playwright');
const BASE = 'http://localhost:8099/';
(async () => {
  const b = await chromium.launch({ executablePath: process.env.PW_CHROMIUM || undefined });
  const p = await (await b.newContext({ viewport: { width: 1500, height: 900 } })).newPage();
  const errs = []; p.on('pageerror', e => errs.push(e.message));
  await p.route('**/fonts.g*/**', r => r.abort());
  const chk = (c, m) => { console.log((c ? 'OK  ' : 'FALLA ') + m); if (!c) errs.push(m); };
  await p.goto(BASE + '?demo'); await p.evaluate(() => localStorage.clear());
  await p.goto(BASE + '?demo&x=1#/'); await p.waitForSelector('.usuarios-demo button'); await p.click('.usuarios-demo button:nth-child(1)'); await p.waitForTimeout(1000);
  await p.goto(BASE + '?demo#/equipo'); await p.waitForTimeout(1300);
  const cols = () => p.$$eval('[data-tabla] tr:first-child th', t => t.map(x => x.textContent.trim().split(' ')[0]));
  chk(!(await cols()).includes('Sábado'), 'por defecto lunes a viernes');
  await p.click('[data-a="finde"]'); await p.waitForTimeout(1200);
  console.log('  columnas:', (await cols()).join(' | '));
  chk((await cols()).includes('Sábado') && (await cols()).includes('Domingo'), 'aparecen sábado y domingo');
  const fila = 'tr:has(b:text-is("Ana Torres"))';
  const cap = async () => Number((await p.$$eval(`[data-tabla] ${fila} td.num`, t => t.map(x => x.textContent)))[1].replace(/\D/g, ''));
  const antes = await cap();
  const sab = await p.$$(`[data-tabla] ${fila} select`);
  const opOficina = await sab[5].$$eval('option', o => o.find(x => /Oficina/.test(x.textContent)).value);
  await sab[5].selectOption(opOficina); await p.waitForTimeout(1000);
  const despues = await cap();
  console.log('  capacidad Ana:', antes, '→', despues);
  chk(despues === antes + 8, 'el sábado trabajado suma capacidad');
  await p.screenshot({ path: 'shots3/finde.png' });
  await p.goto(BASE + '?demo#/plan'); await p.waitForTimeout(1500);
  const pc = await p.$$eval('.tabulator-col-title', t => t.map(x => x.textContent));
  chk(pc.some(x => x.trim() === 'S') && pc.some(x => x.trim() === 'D'), 'Plan semanal muestra sábado y domingo: ' + pc.filter(x => /^[LMXJVSD]$/.test(x.trim())).join(','));
  console.log(errs.length ? 'ERRORES:\n' + errs.join('\n') : 'SIN ERRORES');
  await b.close();
})();
