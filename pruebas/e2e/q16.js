const { chromium } = require('playwright');
const SH = require('path').join(__dirname, 'salida') + '/' + '';
(async () => {
  const b = await chromium.launch({ executablePath: process.env.PW_CHROMIUM || undefined });
  const p = await (await b.newContext({ viewport: { width: 1600, height: 950 } })).newPage();
  const errs = []; p.on('pageerror', e => errs.push(e.message));
  await p.route('**/fonts.g*/**', r => r.abort());
  const B = 'http://localhost:8099/';
  await p.goto(B + '?demo'); await p.evaluate(() => localStorage.clear());
  await p.goto(B + '?demo&x=1#/'); await p.waitForSelector('.usuarios-demo button'); await p.click('.usuarios-demo button:nth-child(1)'); await p.waitForTimeout(1000);
  await p.goto(B + '?demo&a=1#/admin'); await p.waitForTimeout(1200);
  const guardar = async () => { await p.click('.modal-pie .btn-primario'); await p.waitForTimeout(700); };
  await p.click('.admin-item:has-text("Empresas")'); await p.waitForTimeout(500);
  await p.click('[data-a="nueva"]'); await p.waitForTimeout(300); await p.locator('.modal [name="nombre_empresa"]').fill('Constructora Andina'); await guardar();
  const grupos = await p.evaluate(() => [...document.querySelectorAll('.admin-nav-grupo')].map(g => { const items = []; let n = g.nextElementSibling; while (n && !n.classList.contains('admin-nav-grupo')) { if (n.matches('.admin-item')) items.push(n.innerText.trim().replace(/\s+/g, ' ')); n = n.nextElementSibling; } return g.innerText + ': ' + items.join(' | '); }));
  console.log(grupos.join('\n'));
  await p.locator('.admin-item', { hasText: 'Estructura de la empresa' }).click(); await p.waitForTimeout(800);
  console.log('título:', await p.locator('#admin-contenido h2, #admin-contenido h1').first().innerText());
  console.log('pestañas:', (await p.locator('.pestanas-linea button').allInnerTexts()).join(' | '));
  const empresasEnTabla = async () => (await p.locator('tr.est-empresa').allInnerTexts()).map(t => t.split('\n')[0].replace(/\s+/g, ' ').trim());
  console.log('empresas en la tabla:', await empresasEnTabla());
  await p.click('#admin-contenido .admin-cab [data-nuevo="portafolios"], #admin-contenido [data-nuevo="portafolios"][data-area]'); await p.waitForTimeout(300);
  console.log('campos portafolio:', await p.locator('.modal [name]').evaluateAll(es => es.map(e => e.name).join(',')));
  await p.locator('.modal [name="nombre"]').fill('POR_GT'); await guardar();
  console.log('chips:', (await p.locator('.chips-cifras').innerText()).replace(/\s+/g, ' '));
  await p.click('[data-vista="arbol"]'); await p.waitForTimeout(500);
  console.log('árboles en jerárquica:', await p.locator('.org-arbol').count(), '· portafolio nuevo:', await p.locator('.org-portafolio:has-text("POR_GT")').count());
  await p.screenshot({ path: SH + 'q16.png' });
  await p.click('.admin-item:has-text("Estructura de todas")'); await p.waitForTimeout(800);
  console.log('PLATAFORMA vuelve a todas:', await p.locator('.org-arbol').count() || (await empresasEnTabla()).length);
  console.log(errs.length ? errs : 'SIN ERRORES');
  await b.close();
})();
