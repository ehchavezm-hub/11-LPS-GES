const { chromium } = require('playwright');
const BASE = 'http://localhost:8099/';
(async () => {
  const b = await chromium.launch({ executablePath: process.env.PW_CHROMIUM || undefined });
  const p = await (await b.newContext({ viewport: { width: 1400, height: 900 } })).newPage();
  const errs = []; p.on('pageerror', e => errs.push(e.message));
  await p.route('**/fonts.g*/**', r => r.abort());
  const chk = (c, m) => { console.log((c ? 'OK  ' : 'FALLA ') + m); if (!c) errs.push(m); };
  await p.goto(BASE + '?demo'); await p.evaluate(() => localStorage.clear());
  await p.goto(BASE + '?demo&x=1#/'); await p.waitForSelector('.usuarios-demo button'); await p.click('.usuarios-demo button:nth-child(1)'); await p.waitForTimeout(1000);
  await p.goto(BASE + '?demo#/proyectos'); await p.waitForTimeout(1200);
  await p.click('[data-a="nuevo"]'); await p.waitForTimeout(400);
  chk(!(await p.$('.modal [name="cet_id"]')) && !(await p.$('.modal [name="tipo_id"]')), 'sin campos CET ni Tipo');
  const personas = await p.$$eval('.modal .multi.una-columna label', l => l.map(x => x.innerText.replace(/\s+/g, ' ').trim()));
  console.log('  personas:', personas.join(' | '));
  const staff = await p.evaluate(() => JSON.parse(localStorage.getItem('lpsgt-demo-db')).profiles.filter(x => !['consulta', 'pendiente'].includes(x.rol) && x.activo).length);
  chk(personas.length === staff, `todas las personas del equipo (${personas.length} de ${staff})`);
  const tops = await p.$$eval('.modal .multi.una-columna label', l => l.map(x => Math.round(x.getBoundingClientRect().left)));
  chk(new Set(tops).size === 1, 'una sola columna');
  await p.screenshot({ path: 'shots3/proy_form.png' });
  await p.fill('.modal input[name="codigo"]', 'NV-1'); await p.fill('.modal input[name="nombre_corto"]', 'Proyecto sin tipo');
  await p.selectOption('.modal select[name="gerencia_id"]', { index: 1 });
  await p.click('.modal .multi label:has-text("Bruno Salas") input');
  await p.click('.modal-pie button:has-text("Crear")'); await p.waitForTimeout(1200);
  const pr = await p.evaluate(() => { const db = JSON.parse(localStorage.getItem('lpsgt-demo-db')); const x = db.proyectos.find(y => y.codigo === 'NV-1'); return x && { x, l: db.proyecto_lideres.filter(l => l.proyecto_id === x.id).length }; });
  chk(pr && pr.l === 2, 'proyecto creado con 2 líderes');
  const cols = await p.$$eval('.tabulator-col-title', t => t.map(x => x.textContent));
  chk(!cols.includes('CET') && !cols.includes('Tipo') && !cols.includes('Líderes') && !cols.includes('Observaciones'), 'grilla sin CET, Tipo, Líderes ni Observaciones: ' + cols.filter(Boolean).join(', '));
  console.log(errs.length ? 'ERRORES:\n' + errs.join('\n') : 'SIN ERRORES');
  await b.close();
})();
