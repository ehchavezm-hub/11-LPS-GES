const { chromium } = require('playwright');
const BASE = 'http://localhost:8099/';
(async () => {
  const b = await chromium.launch({ executablePath: process.env.PW_CHROMIUM || undefined });
  const p = await (await b.newContext({ viewport: { width: 1500, height: 950 } })).newPage();
  const errs = []; p.on('pageerror', e => errs.push(e.message));
  await p.route('**/fonts.g*/**', r => r.abort());
  const chk = (c, m) => { console.log((c ? 'OK  ' : 'FALLA ') + m); if (!c) errs.push(m); };
  const db = () => p.evaluate(() => { const d = JSON.parse(localStorage.getItem('lpsgt-demo-db')); const v = id => d.lista_valores.find(x => x.id === id)?.valor || null;
    return d.proyectos.filter(x => ['X-001', 'X-002', 'D-101'].includes(x.codigo)).map(x => ({ c: x.codigo, n: x.nombre_corto, g: v(x.gerencia_id), f: v(x.fase_id), pa: v(x.pais_id), e: x.estado, i: x.fecha_inicio, fin: x.fecha_fin })); });
  await p.goto(BASE + '?demo'); await p.evaluate(() => localStorage.clear());
  await p.goto(BASE + '?demo&x=1#/'); await p.waitForSelector('.usuarios-demo button'); await p.click('.usuarios-demo button:nth-child(1)'); await p.waitForTimeout(1000);
  await p.goto(BASE + '?demo#/proyectos'); await p.waitForTimeout(1300);
  const [fc] = await Promise.all([p.waitForEvent('filechooser', { timeout: 5000 }), p.click('[data-a="importar"]')]);
  chk(!!fc, 'el botón abre el selector de archivo');
  await fc.setFiles(__dirname + '/in/proyectos_prueba.xlsx'); await p.waitForTimeout(1500);
  console.log('  ' + (await p.textContent('.modal .modal-cuerpo')).replace(/\s+/g, ' ').slice(0, 420));
  await p.screenshot({ path: 'shots3/import_proy.png' });
  await p.click('.modal-pie button:has-text("Importar")'); await p.waitForTimeout(2500);
  console.log('  toasts:', await p.$$eval('.toast', t => t.map(x => x.textContent).join(' | ')));
  const d = await db(); console.log('  ' + JSON.stringify(d));
  const x1 = d.find(x => x.c === 'X-001'), x2 = d.find(x => x.c === 'X-002'), d1 = d.find(x => x.c === 'D-101');
  chk(x1 && x1.g === 'Gerencia de Obras Civiles' && x1.f === 'Construcción' && x1.i === '2026-01-05' && x1.e === 'activo', 'nuevo X-001 completo con fechas');
  chk(x2 && x2.g === 'Gerencia de Minería' && x2.pa === 'Chile', 'nuevo X-002 con gerencia nueva agregada a la lista');
  chk(d1 && d1.f === 'Cierre' && d1.n === 'Hospital Demo Norte', 'existente D-101 actualizado (fase) sin borrar el nombre');
  chk((await p.textContent('.proy-lista')).includes('Puente Prueba'), 'los importados aparecen en el menú de proyectos');
  console.log(errs.length ? 'ERRORES:\n' + errs.join('\n') : 'SIN ERRORES');
  await b.close();
})();
